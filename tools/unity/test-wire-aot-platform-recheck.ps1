    function Stop-OwnedGradleDaemons {
        param(
            [int[]]$Before = @(),
            [int[]]$Owned = @(),
            [string]$EvidencePath
        )

        # Ownership must be proven by a per-run identifier or a tracked
        # parent/child chain. A PID that merely appeared after the snapshot is
        # not evidence: a sibling Unity build may have started at the same time.
        $after = @(Get-GradleDaemonPids)
        $killable = @($Owned | Where-Object { $_ -and ($after -contains $_) -and ($Before -notcontains $_) } |
            Sort-Object -Unique)
        $preserved = @($after | Where-Object { $killable -notcontains $_ } | Sort-Object -Unique)

        if ($EvidencePath) {
            $lines = @(
                "before=$($Before -join ',')",
                "after=$($after -join ',')",
                "owned=$($Owned -join ',')",
                "killable=$($killable -join ',')",
                "preserved=$($preserved -join ',')",
                "action=$(if ($killable.Count -gt 0) { 'kill-owned' } else { 'preserve-unproven' })"
            )
            Write-Utf8NoBom -Path $EvidencePath -Text (($lines -join "`r`n") + "`r`n")
        }

        foreach ($daemonPid in $killable) {
            try {
                & (Join-Path $env:SystemRoot 'System32\taskkill.exe') /PID $daemonPid /T /F 2>&1 | Out-Null
            }
            catch { }
        }

        return [pscustomobject]@{
            Before    = $Before
            After     = $after
            Owned     = $Owned
            Killable  = $killable
            Preserved = $preserved
        }
    }

