                        Add-Artifact -Path $logcatPath -Role 'android-logcat'
                        Add-Artifact -Path "$RunDir\android-logcat-final.stdout.log" -Role 'android-logcat-final-stdout'
                        Add-Artifact -Path "$RunDir\android-logcat-final.stderr.log" -Role 'android-logcat-final-stderr'

                        $uninstall = Invoke-NativeProcess -FilePath $adbPath -Arguments @('-s', $serial, 'uninstall', 'com.mahjong.aotsmoke') -TimeoutSeconds 30 `
                            -LogPrefix (Join-Path $RunDir 'android-adb-uninstall')
                        Add-Artifact -Path "$RunDir\android-adb-uninstall.stdout.log" -Role 'android-adb-uninstall'

                        if ($runtimeFailure) {
                            Add-Result -Name 'Android IL2CPP runtime' -Status FAIL -Detail "$runtimeFailure; serial=$serial; log=$logcatPath" -ExitCode 1 -Evidence $logcatPath
                            $androidRuntimeStatus = 'FAIL'
                        }
                        elseif ($marker) {
                            Add-Result -Name 'Android IL2CPP runtime' -Status PASS -Detail ("serial=$serial; logcat marker: " + $marker.Trim()) -ExitCode 0 -Evidence $logcatPath
                            $androidRuntimeStatus = 'PASS'
                        }
                        else {
                            Add-Result -Name 'Android IL2CPP runtime' -Status FAIL -Detail "no [WireAotSmoke] PASS marker after clear/start; serial=$serial; log=$logcatPath" -ExitCode 1 -Evidence $logcatPath
                            $androidRuntimeStatus = 'FAIL'
                        }
                    }
                }
                catch {
                    Add-Result -Name 'Android IL2CPP runtime' -Status FAIL -Detail ($_.Exception.Message + " at " + $_.ScriptStackTrace) -ExitCode 1
                    $androidRuntimeStatus = 'FAIL'
                }
            }
            else {
                Add-Result -Name 'Android IL2CPP runtime' -Status NOT_RUN -Detail "build status is $androidBuildStatus; no APK to install" -ExitCode -999
                $androidRuntimeStatus = 'NOT_RUN'
            }
        }
    }
    $script:TargetInfo['android'] = [ordered]@{ build = $androidBuildStatus; runtime = $androidRuntimeStatus }

    # iOS cannot be exercised on Windows.
    Add-Result -Name 'iOS IL2CPP' -Status BLOCKED -Detail 'requires macOS/Xcode and an iOS device; unavailable on Windows' -ExitCode 2
    $script:TargetInfo['ios'] = [ordered]@{ build = 'BLOCKED'; runtime = 'NOT_RUN' }

    # -----------------------------------------------------------------------
    # Machine-readable summary and hashes of every artifact under RunDir.
    # -----------------------------------------------------------------------
    # Stop the transcript before hashing so console.log is not held open.
    try { Stop-Transcript | Out-Null } catch { }
    Get-ChildItem -LiteralPath $RunDir -Recurse -File | ForEach-Object {
        $file = $_
        $existing = $script:Artifacts | Where-Object { $_.path -eq $file.FullName }
        if (-not $existing) {
            Add-Artifact -Path $file.FullName -Role 'artifact'
        }
    }

    $exitCode = if ($script:Failed) { 1 } elseif ($script:Blocked -or $script:NotRun) { 2 } else { 0 }
    $summary = [ordered]@{
        schemaVersion = 1
        task = 'P2.2 current-platform recheck'
        baseline = $BaselineCommit
        branch = $ExpectedBranch
        stamp = $Stamp
        runId = Split-Path -Leaf $RunDir
        startedAt = $Stamp
        finishedAt = (Get-Date).ToString('o')
        runDir = $RunDir
        tempRoot = if ($KeepTemp) { $script:TempRoot } else { $null }
        overallExit = $exitCode
        results = $script:Results
        targets = $script:TargetInfo
        environment = $script:EnvironmentInfo
        artifacts = $script:Artifacts
    }
    Write-Utf8NoBom -Path (Join-Path $RunDir 'summary.json') -Text ($summary | ConvertTo-Json -Depth 10)

    $table = $script:Results | Format-Table -AutoSize | Out-String
    Write-Utf8NoBom -Path (Join-Path $RunDir 'results.txt') -Text ($table +
        ("`r`nsummary  : pass={0} fail={1} blocked={2} not_run={3} exit={4}`r`n" -f
        @($script:Results | Where-Object { $_.status -eq 'PASS' }).Count,
        @($script:Results | Where-Object { $_.status -eq 'FAIL' }).Count,
        @($script:Results | Where-Object { $_.status -eq 'BLOCKED' }).Count,
        @($script:Results | Where-Object { $_.status -eq 'NOT_RUN' }).Count,
        $exitCode))
    Write-Host ""
    Write-Host $table
    Write-Host ("summary  : pass={0} fail={1} blocked={2} not_run={3} exit={4}" -f
        @($script:Results | Where-Object { $_.status -eq 'PASS' }).Count,
        @($script:Results | Where-Object { $_.status -eq 'FAIL' }).Count,
        @($script:Results | Where-Object { $_.status -eq 'BLOCKED' }).Count,
        @($script:Results | Where-Object { $_.status -eq 'NOT_RUN' }).Count,
        $exitCode)
    Write-Host "artifacts: $RunDir"

    $global:LASTEXITCODE = $exitCode
    exit $exitCode
}
catch {
    $message = "FATAL: $($_.Exception.GetType().FullName): $($_.Exception.Message)`r`n$($_.ScriptStackTrace)"
    Write-Host $message -ForegroundColor Red
    try { Write-Utf8NoBom -Path (Join-Path $RunDir 'fatal.txt') -Text $message } catch { }
    Add-Result -Name 'Wrapper fatal' -Status FAIL -Detail $message -ExitCode 1
    try {
        $summary = [ordered]@{
            schemaVersion = 1
            task = 'P2.2 current-platform recheck'
            baseline = $BaselineCommit
            branch = $ExpectedBranch
            stamp = $Stamp
            runDir = $RunDir
            fatal = $message
            overallExit = 1
            results = $script:Results
            targets = $script:TargetInfo
            environment = $script:EnvironmentInfo
        }
        Write-Utf8NoBom -Path (Join-Path $RunDir 'summary.json') -Text ($summary | ConvertTo-Json -Depth 10)
    }
    catch { }
    exit 1
}
finally {
    try {
        if ($script:TempRoot -and (Test-Path -LiteralPath $script:TempRoot) -and -not $KeepTemp) {
            Remove-TempRoot
        }
        elseif ($script:TempRoot -and $KeepTemp) {
            Write-Host "temp kept: $($script:TempRoot)"
        }
    }
    catch {
        Write-Warning "temp cleanup skipped: $($_.Exception.Message)"
    }
    $env:TEMP = $script:OriginalTemp
    $env:TMP = $script:OriginalTmp
    try { Stop-Transcript | Out-Null } catch { }
}
