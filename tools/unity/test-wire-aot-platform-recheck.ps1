function Write-Utf8NoBom {
    param([Parameter(Mandatory)][string]$Path, [AllowEmptyString()][string]$Text)
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Force -Path $dir | Out-Null
    }
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $Text, $utf8)
}

function Add-Result {
    param(
        [Parameter(Mandatory)][string]$Name,
        [Parameter(Mandatory)][ValidateSet('PASS', 'FAIL', 'BLOCKED', 'NOT_RUN', 'INFO')][string]$Status,
        [string]$Detail,
        [int]$ExitCode = -999,
        [double]$DurationSec = -1,
        [string]$Evidence
    )

    $script:Results.Add([pscustomobject]@{
        name = $Name
        status = $Status
        exit = $ExitCode
        durationSec = $DurationSec
        detail = $Detail
        evidence = $Evidence
    })

    $color = switch ($Status) {
        'PASS' { 'Green' }
        'FAIL' { 'Red' }
        'BLOCKED' { 'Yellow' }
        'NOT_RUN' { 'Gray' }
        default { 'Cyan' }
    }
    Write-Host ("{0,-8} {1,-34} {2}" -f $Status, $Name, $Detail) -ForegroundColor $color
    if ($Status -eq 'FAIL') { $script:Failed = $true }
    elseif ($Status -eq 'BLOCKED') { $script:Blocked = $true }
    elseif ($Status -eq 'NOT_RUN') { $script:NotRun = $true }
}

function ConvertTo-NativeArgument {
    param([string]$Value)

    if ($Value -notmatch '[\s"]') {
        return $Value
    }

    return '"' + ($Value -replace '(\\*)"', '$1$1\"') + '"'
}

function Stop-OwnedProcessTree {
    param(
        [Parameter(Mandatory)][System.Diagnostics.Process]$Process,
        [hashtable]$TrackedInstances = @{},
        [object]$RootCreationDate = $null,
        [string]$EvidencePath
    )

    # Ownership is a PID + creation-time instance, never a bare PID or a bare
    # ParentProcessId. A tracked instance is recorded while the root was alive;
    # at kill time the current process must still match that creation time.
    # No taskkill /T recursion is used: recursive CID lookup could re-expand the
    # set to a reused PID or a stale parent link.
    $all = @(Get-CimInstance Win32_Process -ErrorAction SilentlyContinue)
    $current = @{}
    foreach ($item in $all) {
        $current[[int]$item.ProcessId] = $item
    }

    $verified = New-Object System.Collections.Generic.List[int]
    foreach ($key in $TrackedInstances.Keys) {
        $trackedId = 0
        if (-not [int]::TryParse([string]$key, [ref]$trackedId)) { continue }
        if ($trackedId -le 0 -or $trackedId -eq $PID) { continue }
        if (-not $current.ContainsKey($trackedId)) { continue }
        $trackedDate = $null
        try { $trackedDate = [datetime]$TrackedInstances[$key] } catch { }
        $currentDate = $null
        try { $currentDate = [datetime]$current[$trackedId].CreationDate } catch { }
        if (-not $trackedDate -or -not $currentDate) { continue }
        if ($currentDate -eq $trackedDate) {
            $verified.Add($trackedId)
        }
    }

    if ($EvidencePath) {
        $trackedKeys = @($TrackedInstances.Keys | Sort-Object)
        $preservedTracked = @($trackedKeys | Where-Object { $verified -notcontains [int]$_ })
        $evidenceLines = @(
            "rootPid=$($Process.Id)",
            "rootExited=$($Process.HasExited)",
            "tracked=$($trackedKeys -join ',')",
            "verified=$($verified -join ',')",
            "preservedTracked=$($preservedTracked -join ',')",
            "action=$(if ($verified.Count -gt 0) { 'kill-verified-instances' } else { 'preserve-unproven' })"
        )
        [IO.File]::WriteAllText($EvidencePath, (($evidenceLines -join "`r`n") + "`r`n"), (New-Object Text.UTF8Encoding($false)))
    }

    # If the root already exited, a new process that happens to reuse its PID is
    # not ours. Only tracked instances with matching creation times are eligible.
    if ($Process.HasExited) {
        foreach ($targetId in $verified) {
            try {
                $taskkill = Join-Path $env:SystemRoot 'System32\taskkill.exe'
                & $taskkill /PID $targetId /F 2>&1 | Out-Null
            }
            catch { }
        }
        return
    }

    # Root is still alive: verify its exact creation time from the same CIM
    # field captured while it was alive before killing anything.
    if (-not $current.ContainsKey($Process.Id)) { return }
    if (-not $RootCreationDate) { return }
    $expectedRootDate = [datetime]$RootCreationDate
    $rootDate = $null
    try { $rootDate = [datetime]$current[$Process.Id].CreationDate } catch { }
    if (-not $rootDate -or $rootDate -ne $expectedRootDate) { return }

    foreach ($targetId in $verified) {
        try {
            $taskkill = Join-Path $env:SystemRoot 'System32\taskkill.exe'
            & $taskkill /PID $targetId /F 2>&1 | Out-Null
        }
        catch { }
    }

    try {
        $taskkill = Join-Path $env:SystemRoot 'System32\taskkill.exe'
        & $taskkill /PID $Process.Id /F 2>&1 | Out-Null
    }
    catch {
        try { $Process.Kill() } catch { }
    }
}
function Invoke-NativeProcess {
    param(
        [Parameter(Mandatory)][string]$FilePath,
        [Parameter(Mandatory)][string[]]$Arguments,
        [int]$TimeoutSeconds = 0,
        [string]$LogPrefix,
        [string]$WorkingDirectory,
        [hashtable]$Environment = @{}
    )

    $stdoutPath = "$LogPrefix.stdout.log"
    $stderrPath = "$LogPrefix.stderr.log"
    $argumentLine = ($Arguments | ForEach-Object { ConvertTo-NativeArgument $_ }) -join ' '
    $started = Get-Date

    $startInfo = New-Object System.Diagnostics.ProcessStartInfo
    $startInfo.FileName = $FilePath
    $startInfo.Arguments = $argumentLine
    $startInfo.UseShellExecute = $false
    $startInfo.CreateNoWindow = $true
    $startInfo.RedirectStandardOutput = $true
    $startInfo.RedirectStandardError = $true
    if ($WorkingDirectory) { $startInfo.WorkingDirectory = $WorkingDirectory }
    foreach ($key in $Environment.Keys) {
        $startInfo.EnvironmentVariables[$key] = [string]$Environment[$key]
    }

    $process = New-Object System.Diagnostics.Process
    $process.StartInfo = $startInfo
    $null = $process.Start()
    $stdoutTask = $process.StandardOutput.ReadToEndAsync()
    $stderrTask = $process.StandardError.ReadToEndAsync()

    $deadline = if ($TimeoutSeconds -gt 0) { (Get-Date).AddSeconds($TimeoutSeconds) } else { [DateTime]::MaxValue }
    $timedOut = $false
    $trackedInstances = @{}

    if ($TimeoutSeconds -gt 0) {
        $rootCreationDate = $null

        while (-not $process.HasExited) {
            # Record only process instances observed while the root is alive.
            # Each entry is PID + creation time; a later PID reuse cannot match.
            if ($process.HasExited -eq $false) {
                $snapshot = @(Get-CimInstance Win32_Process -ErrorAction SilentlyContinue)
                $current = @{}
                $byParent = @{}
                foreach ($item in $snapshot) {
                    $current[[int]$item.ProcessId] = $item
                    $parentId = [int]$item.ParentProcessId
                    if (-not $byParent.ContainsKey($parentId)) {
                        $byParent[$parentId] = New-Object System.Collections.Generic.List[int]
                    }
                    $byParent[$parentId].Add([int]$item.ProcessId)
                }
                if ($current.ContainsKey($process.Id)) {
                    $rootDate = $null
                    try { $rootDate = [datetime]$current[$process.Id].CreationDate } catch { }
                    if ($rootDate) {
                        if (-not $rootCreationDate) { $rootCreationDate = $rootDate }
                    }
                    if ($rootDate -and $rootDate -eq $rootCreationDate) {
                        $queue = New-Object System.Collections.Generic.Queue[int]
                        $queue.Enqueue($process.Id)
                        while ($queue.Count -gt 0) {
                            $currentId = $queue.Dequeue()
                            if (-not $byParent.ContainsKey($currentId)) { continue }
                            $parentDate = $null
                            try { $parentDate = [datetime]$current[$currentId].CreationDate } catch { }
                            if (-not $parentDate) { continue }
                            foreach ($childId in $byParent[$currentId]) {
                                $childDate = $null
                                try { $childDate = [datetime]$current[$childId].CreationDate } catch { }
                                # Per-edge instance check: a child born before the
                                # already-proven direct parent cannot be its child.
                                if ($childDate -and $childDate -ge $parentDate) {
                                    $trackedInstances[[string]$childId] = $childDate
                                    $queue.Enqueue($childId)
                                }
                            }
                        }
                    }
                }
            }

            $remainingMs = [int][Math]::Max(0, ($deadline - (Get-Date)).TotalMilliseconds)
            if ($remainingMs -le 0) { $timedOut = $true; break }
            $sliceMs = [int][Math]::Min(1000, $remainingMs)
            if ($process.WaitForExit($sliceMs)) { break }
        }
    }
    else {
        $process.WaitForExit()
    }

    if (-not $timedOut -and $process.HasExited) {
        $drainMs = [int][Math]::Max(0, ($deadline - (Get-Date)).TotalMilliseconds)
        $tasks = @($stdoutTask, $stderrTask)
        $drained = [System.Threading.Tasks.Task]::WaitAll($tasks, $drainMs)
        if (-not $drained) { $timedOut = $true }
    }

    if ($timedOut) {
        Stop-OwnedProcessTree -Process $process -TrackedInstances $trackedInstances -RootCreationDate $rootCreationDate -EvidencePath "$LogPrefix.timeout-processes.txt"
        # Closing the read handles breaks a pipe still held by a descendant;
        # otherwise ReadToEndAsync could wait forever after the parent exited.
        try { $process.StandardOutput.Close() } catch { }
        try { $process.StandardError.Close() } catch { }
        try { [System.Threading.Tasks.Task]::WaitAll(@($stdoutTask, $stderrTask), 500) | Out-Null } catch { }
        try { $process.WaitForExit(500) | Out-Null } catch { }
    }
    $stdout = ''
    $stderr = ''
    if ($stdoutTask.IsCompleted) {
        try { $stdout = $stdoutTask.Result } catch { $stdout = "<stdout read failed: $($_.Exception.Message)>" }
    }
    else {
        $stdout = '<stdout drain timeout>'
    }
    if ($stderrTask.IsCompleted) {
        try { $stderr = $stderrTask.Result } catch { $stderr = "<stderr read failed: $($_.Exception.Message)>" }
    }
    else {
        $stderr = '<stderr drain timeout>'
    }
    Write-Utf8NoBom -Path $stdoutPath -Text $stdout
    Write-Utf8NoBom -Path $stderrPath -Text $stderr

    $duration = [math]::Round(((Get-Date) - $started).TotalSeconds, 2)
    $exitCode = if ($timedOut) { -1 } else { $process.ExitCode }
    return [pscustomobject]@{
        ExitCode     = $exitCode
        TimedOut     = $timedOut
        DurationSec  = $duration
        StdoutPath   = $stdoutPath
        StderrPath   = $stderrPath
        Stdout       = $stdout
        Stderr       = $stderr
        CommandLine  = "$FilePath $argumentLine"
    }
}

function Get-Sha256 {
    param([Parameter(Mandatory)][string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) { return $null }
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash
}

function Add-Artifact {
    param([Parameter(Mandatory)][string]$Path, [string]$Role)

    if (-not (Test-Path -LiteralPath $Path)) { return }
    $item = Get-Item -LiteralPath $Path
    if ($item.PSIsContainer) { return }
    $script:Artifacts.Add([pscustomobject]@{
        path = $item.FullName
        role = $Role
        bytes = $item.Length
        sha256 = (Get-Sha256 -Path $item.FullName)
    })
}

function Initialize-TempRoot {
    if ($script:TempRoot) { return $script:TempRoot }

    $driveRoot = 'D:\temp'
    if (-not (Test-Path -LiteralPath $driveRoot)) {
        throw "Required D: temp root is missing: $driveRoot"
    }
    $leaf = 'mahjong-p22-recheck-' + [guid]::NewGuid().ToString('N')
    $script:TempRoot = Join-Path $driveRoot $leaf
    New-Item -ItemType Directory -Force -Path $script:TempRoot | Out-Null

    # Process-scoped only. The machine/user TEMP/TMP registry values are untouched.
    $env:TEMP = $script:TempRoot
    $env:TMP = $script:TempRoot
    return $script:TempRoot
}

function Remove-TreeRobust {
    param([Parameter(Mandatory)][string]$Path)

    # Normal path first; retry with the extended-length prefix for Unity
    # PackageCache paths that exceed MAX_PATH. The caller has already resolved
    # and validated the absolute target.
    try {
        Remove-Item -LiteralPath $Path -Recurse -Force -ErrorAction Stop
        return
    }
    catch {
        $firstError = $_.Exception.Message
    }

    $extended = if ($Path.StartsWith('\\?\')) { $Path } else { '\\?\' + $Path }
    try {
        Get-ChildItem -LiteralPath $extended -Recurse -Force -ErrorAction SilentlyContinue |
            ForEach-Object { try { $_.Attributes = [System.IO.FileAttributes]::Normal } catch { } }
        Remove-Item -LiteralPath $extended -Recurse -Force -ErrorAction Stop
    }
    catch {
        throw "Recursive delete failed for $Path; first=$firstError; extended=$($_.Exception.Message)"
    }
}

function Remove-CheckedTree {
    param([Parameter(Mandatory)][string]$Path)

    if (-not (Test-Path -LiteralPath $Path)) { return }
    if (-not $script:TempRoot) { throw "Refusing cleanup before the temp root is initialized: $Path" }

    $resolvedRoot = (Resolve-Path -LiteralPath $script:TempRoot).Path.TrimEnd('\')
    $resolved = (Resolve-Path -LiteralPath $Path).Path.TrimEnd('\')
    if (-not $resolved.StartsWith($resolvedRoot + '\', [StringComparison]::OrdinalIgnoreCase) -and
        $resolved -ne $resolvedRoot) {
        throw "Refusing recursive delete outside this run's temp root: $resolved (root $resolvedRoot)"
    }

    Remove-TreeRobust -Path $resolved
}

function Remove-TempRoot {
    if (-not $script:TempRoot -or -not (Test-Path -LiteralPath $script:TempRoot)) { return }

    $resolved = (Resolve-Path -LiteralPath $script:TempRoot).Path.TrimEnd('\')
    $leaf = Split-Path -Leaf $resolved
    $parent = Split-Path -Parent $resolved
    if ($parent.TrimEnd('\') -ne 'D:\temp' -or
        -not $leaf.StartsWith('mahjong-p22-recheck-', [StringComparison]::Ordinal)) {
        throw "Refusing recursive delete of unverified temp root: $resolved"
    }

    Remove-TreeRobust -Path $resolved
}

function Invoke-Git {
    param([string[]]$Arguments)
    $output = & git -C $RepoRoot @Arguments 2>&1
    return [pscustomobject]@{ ExitCode = $LASTEXITCODE; Text = (($output | Out-String).Trim()) }
}

# ---------------------------------------------------------------------------
# Guard: frozen baseline, expected branch, clean tracked worktree.
# ---------------------------------------------------------------------------
$guardLines = New-Object System.Collections.Generic.List[string]
try {
    $head = (Invoke-Git @('rev-parse', 'HEAD')).Text
    $branch = (Invoke-Git @('rev-parse', '--abbrev-ref', 'HEAD')).Text
    $status = (Invoke-Git @('-c', 'core.quotepath=false', 'status', '--porcelain=v1')).Text
    $guardLines.Add("head=$head")
    $guardLines.Add("branch=$branch")
    $guardLines.Add("status=$status")
    if ($branch -ne $ExpectedBranch) { throw "Branch mismatch: $branch != $ExpectedBranch" }

    # Accept the frozen baseline itself, or a delivery commit that is a
    # descendant of it and only adds this task's wrapper/report. This keeps the
    # guard runnable from the committed delivery without weakening the baseline.
    $headMode = 'frozen-baseline'
    $baselineDiff = @()
    if ($head -ne $BaselineCommit) {
        $ancestor = (Invoke-Git @('merge-base', '--is-ancestor', $BaselineCommit, $head)).ExitCode
        if ($ancestor -ne 0) { throw "HEAD is not a descendant of $BaselineCommit : $head" }
        $diffText = (Invoke-Git @('-c', 'core.quotepath=false', 'diff', '--name-only', "$BaselineCommit..$head")).Text
        $baselineDiff = @($diffText -split "`r?`n" | Where-Object { $_ })
        $unexpectedDiff = @($baselineDiff | Where-Object {
            $file = $_
            $file -ne 'tools/unity/test-wire-aot-platform-recheck.ps1' -and
            $file -notmatch '^doc/.+/V5-P2\.2-PLATFORM-RECHECK-20261026\.md$'
        })
        if ($unexpectedDiff.Count -gt 0) {
            throw "HEAD changes files outside this task: $($unexpectedDiff -join '; ')"
        }
        $headMode = 'delivery-commit'
    }
    $guardLines.Add("head_mode=$headMode")
    $guardLines.Add("baseline_diff=$($baselineDiff -join ',')")

    # This task is allowed to create its own wrapper and report. Nothing else may
    # be dirty or untracked when the recheck starts.
    $wrapperRel = $PSCommandPath.Substring($RepoRoot.Length + 1).Replace('\', '/')
    $allowedUntracked = @($wrapperRel)
    $statusLines = @($status -split "`r?`n" | Where-Object { $_ })
    $unexpected = @($statusLines | Where-Object {
        $line = $_
        $line -ne "?? $wrapperRel" -and
        $line -notmatch '^\?\? doc/.+/V5-P2\.2-PLATFORM-RECHECK-20261026\.md$'
    })
    if ($unexpected.Count -gt 0) { throw "Worktree has unexpected changes: $($unexpected -join '; ')" }
    $guardLines.Add("allowed_untracked=$($allowedUntracked -join ',')")
    if (-not ((Invoke-Git @('check-ignore', '-q', "build/p22-platform-recheck/$Stamp")).ExitCode -eq 0)) {
        throw 'build/p22-platform-recheck is not git-ignored'
    }
    Write-Utf8NoBom -Path (Join-Path $RunDir 'baseline-guard.txt') -Text (($guardLines -join "`r`n") + "`r`n")
    Add-Result -Name 'Baseline guard' -Status PASS -Detail "HEAD=$head mode=$headMode branch=$branch clean=true" -ExitCode 0
}
catch {
    Write-Utf8NoBom -Path (Join-Path $RunDir 'baseline-guard.txt') -Text (($guardLines -join "`r`n") + "`r`nFAIL: $($_.Exception.Message)")
    Add-Result -Name 'Baseline guard' -Status FAIL -Detail $_.Exception.Message -ExitCode 1
    throw
}

Start-Transcript -Path (Join-Path $RunDir 'console.log') -Force | Out-Null

try {
    Initialize-TempRoot | Out-Null
    $freeGb = [math]::Round((Get-PSDrive D).Free / 1GB, 2)
    Add-Result -Name 'Host resources' -Status $(if ($freeGb -ge 20) { 'PASS' } else { 'BLOCKED' }) `
        -Detail "D: free=${freeGb}GB; TEMP=$env:TEMP; TMP=$env:TMP" -ExitCode 0

    # -----------------------------------------------------------------------
    # Unity editor selection from ProjectVersion.txt
    # -----------------------------------------------------------------------
    $projectVersionPath = Join-Path $RepoRoot 'unity\Mahjong.Unity\ProjectSettings\ProjectVersion.txt'
    $projectVersionText = Get-Content -LiteralPath $projectVersionPath -Raw
    $versionMatch = [regex]::Match($projectVersionText, 'm_EditorVersion:\s*(\S+)')
    if (-not $versionMatch.Success) { throw "Cannot parse m_EditorVersion from $projectVersionPath" }
    $projectVersion = $versionMatch.Groups[1].Value
    $revisionMatch = [regex]::Match($projectVersionText, 'm_EditorVersionWithRevision:\s*\S+\s*\(([0-9a-f]+)\)')
    $projectRevision = if ($revisionMatch.Success) { $revisionMatch.Groups[1].Value } else { '' }

    $candidateEditors = New-Object System.Collections.Generic.List[string]
    if ($UnityPath) { $candidateEditors.Add($UnityPath) }
    if ($env:UNITY_PATH) { $candidateEditors.Add($env:UNITY_PATH) }
    foreach ($root in @('D:\Unity\Hub\Editor', 'C:\Program Files\Unity\Hub\Editor')) {
        if (-not (Test-Path -LiteralPath $root)) { continue }
        Get-ChildItem -LiteralPath $root -Directory -ErrorAction SilentlyContinue | ForEach-Object {
            $candidateEditors.Add((Join-Path $_.FullName 'Editor\Unity.exe'))
        }
    }

    $unity = $null
    $unityCandidates = New-Object System.Collections.Generic.List[object]
    foreach ($candidate in ($candidateEditors | Select-Object -Unique)) {
        if (-not (Test-Path -LiteralPath $candidate)) { continue }
        $versionInfo = [System.Diagnostics.FileVersionInfo]::GetVersionInfo($candidate)
        $unityCandidates.Add([pscustomobject]@{
            Path = $candidate
            FileVersion = $versionInfo.FileVersion
            ProductVersion = $versionInfo.ProductVersion
        })
        if ($versionInfo.ProductVersion -and
            ($versionInfo.ProductVersion -match ('^' + [regex]::Escape($projectVersion) + '([_+].*)?$'))) {
            $unity = $candidate
            break
        }
    }

    $unityVersionLog = ($unityCandidates | ForEach-Object {
        "path=$($_.Path); fileVersion=$($_.FileVersion); productVersion=$($_.ProductVersion)"
    }) -join "`r`n"
    Write-Utf8NoBom -Path (Join-Path $RunDir 'unity-candidates.txt') -Text $unityVersionLog

    if (-not $unity) {
        Add-Result -Name 'Unity editor selection' -Status BLOCKED `
            -Detail "No editor matching ProjectVersion=$projectVersion; candidates=$($unityCandidates.Count)" -ExitCode 2 `
            -Evidence (Join-Path $RunDir 'unity-candidates.txt')
        $script:Blocked = $true
    }
    else {
        $unityInfo = [System.Diagnostics.FileVersionInfo]::GetVersionInfo($unity)
        $script:EnvironmentInfo['unity'] = [ordered]@{
            path = $unity
            projectVersion = $projectVersion
            projectRevision = $projectRevision
            fileVersion = $unityInfo.FileVersion
            productVersion = $unityInfo.ProductVersion
            sha256 = (Get-Sha256 -Path $unity)
        }
        Add-Result -Name 'Unity editor selection' -Status PASS `
            -Detail "path=$unity productVersion=$($unityInfo.ProductVersion) projectVersion=$projectVersion" -ExitCode 0 `
            -Evidence (Join-Path $RunDir 'unity-candidates.txt')
    }

    $editorData = if ($unity) { Join-Path (Split-Path -Parent $unity) 'Data' } else { $null }
    $il2cppExe = if ($editorData) { Join-Path $editorData 'il2cpp\build\deploy\il2cpp.exe' } else { $null }
    $androidPlayer = if ($editorData) { Join-Path $editorData 'PlaybackEngines\AndroidPlayer' } else { $null }
    $winSupport = if ($editorData) { Join-Path $editorData 'PlaybackEngines\windowsstandalonesupport' } else { $null }
    $winIl2cppModule = $null
