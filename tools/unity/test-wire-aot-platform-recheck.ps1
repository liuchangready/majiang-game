<#
.SYNOPSIS
    P2.2 platform recheck wrapper for the generated Wire codec.

.DESCRIPTION
    Owns one exclusive artifact directory per run and records a machine-readable
    summary. It reuses the probe sources generated by tools/unity/test-wire-aot.ps1
    but fixes the confirmed local defects in that script for this recheck:

      * stages the real managed dependency closure of the probe (including
        System.Runtime.CompilerServices.Unsafe), not a four-file list;
      * selects the Unity editor from the project's ProjectVersion.txt instead of
        the lexicographically newest editor;
      * propagates native exit codes, timeouts and process-tree termination;
      * confines recursive cleanup to this run's own temp root.

    It never edits the shared Unity project, ProjectSettings, Assets/Plugins
    contents, the tracked link.xml, WireAotSmoke.cs, schema or generated code.
    All writes go to build/p22-platform-recheck/<stamp> and to an in-process
    TEMP/TMP directory on D:.

.PARAMETER Target
    All (default), DotNet, Windows or Android. iOS is always reported BLOCKED.

.PARAMETER KeepTemp
    Keep the isolated Unity project copies under the D: temp root.

.NOTES
    Exit: 0 only when every requested target is PASS; 1 when any target FAILs;
    2 when any target is BLOCKED or NOT_RUN.
#>
